import 'package:flutter/material.dart';
import 'package:flutter_localizations/flutter_localizations.dart';

class AppLocalizations {
  final Locale locale;
  AppLocalizations(this.locale);

  static AppLocalizations of(BuildContext context) {
    return Localizations.of<AppLocalizations>(context, AppLocalizations)!;
  }

  static final List<LocalizationsDelegate<dynamic>> localizationsDelegates = [
    _AppLocalizationsDelegate(),
    GlobalMaterialLocalizations.delegate,
    GlobalWidgetsLocalizations.delegate,
    GlobalCupertinoLocalizations.delegate,
  ];

  static const supportedLocales = [
    Locale('en'),
    Locale('es'),
    Locale('fr'),
    Locale('ar'),
    Locale('pt'),
    Locale('de'),
    Locale('it'),
    Locale('ru'),
    Locale('zh'),
    Locale('ja'),
    Locale('ko'),
  ];

  String tr(String key, [Map<String, String>? params]) {
    final lang = locale.languageCode;
    final translations = _allTranslations[key];
    if (translations == null) return key;
    var text = translations[lang] ?? translations['en'] ?? key;
    if (params != null) {
      for (final e in params.entries) {
        text = text.replaceAll('{$e.key}', e.value);
      }
    }
    return text;
  }

  String get localeName {
    switch (locale.languageCode) {
      case 'en': return 'English';
      case 'es': return 'Español';
      case 'fr': return 'Français';
      case 'ar': return 'العربية';
      case 'pt': return 'Português';
      case 'de': return 'Deutsch';
      case 'it': return 'Italiano';
      case 'ru': return 'Русский';
      case 'zh': return '中文';
      case 'ja': return '日本語';
      case 'ko': return '한국어';
      default: return 'English';
    }
  }
}

class _AppLocalizationsDelegate extends LocalizationsDelegate<AppLocalizations> {
  @override
  bool isSupported(Locale locale) =>
      AppLocalizations.supportedLocales.any((l) => l.languageCode == locale.languageCode);

  @override
  Future<AppLocalizations> load(Locale locale) => Future.value(AppLocalizations(locale));

  @override
  bool shouldReload(_AppLocalizationsDelegate old) => false;
}

